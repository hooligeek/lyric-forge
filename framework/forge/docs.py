def asset_link(out_root: Path, subdir: str, target: Path) -> str:
    """Link from a generated page to a committed asset.

    Depth is counted from the repository root to the page's own directory, not
    from the subdirectory name — getting that wrong made every artwork link one
    level short. And if the output root is outside the repo (a wiki clone, say),
    no relative path can reach the assets at all, so fall back to an absolute
    file URL and let `docs` report the caveat rather than emitting links that
    quietly 404.
    """
    try:
        page_dir = (out_root / subdir).resolve().relative_to(config_mod.REPO_ROOT)
    except ValueError:
        return target.resolve().as_uri()
    depth = len(page_dir.parts)
    return "../" * depth + target.relative_to(config_mod.REPO_ROOT).as_posix()


def assets_reachable(out_root: Path) -> bool:
    try:
        out_root.resolve().relative_to(config_mod.REPO_ROOT)
        return True
    except ValueError:
        return False


def _track_stats(t: dict) -> list[str]:
    a = t.get("analysis") or {}
    rhythm, tonal, asr, dsp = (
        a.get("rhythm") or {}, a.get("tonal") or {}, a.get("asr") or {}, a.get("dsp") or {}
    )
    bits: list[str] = []
    declared = ledger_mod.get_nested(t, "suno.declared_bpm")
    measured = t.get("measured_bpm")
    if declared and measured:
        agree = "" if rhythm.get("tempo_locked") else "  ⚠ disagree"
        bits.append(f"**Tempo** {measured:.0f} BPM measured / {declared} declared{agree}")
    elif measured:
        bits.append(f"**Tempo** {measured:.0f} BPM measured")
    elif declared:
        bits.append(f"**Tempo** {declared} BPM declared")
    if t.get("duration_s"):
        m, s = divmod(int(t["duration_s"]), 60)
        bits.append(f"**Length** {m}:{s:02d}")
    if asr.get("word_accuracy") is not None:
        verdict = asr.get("verdict", "")
        flag = "" if verdict == "ok" else f"  ⚠ {verdict}"
        bits.append(f"**Sheet match** {asr['word_accuracy']:.0%}{flag}")
    if dsp.get("peak_dbfs") is not None:
        bits.append(f"**Peak** {dsp['peak_dbfs']} dBFS")
    return bits


def _catalog_band(cfg: Config, slug: str, out_root: Path) -> str:
    spec = context_mod.band_spec(cfg, slug)
    bblock = spec.get("band") or {}
    sonic = spec.get("sonic") or {}
    all_rows = ledger_mod.load_band_tracks(cfg.bands[slug])

    # Releases and work in progress are counted separately everywhere below. A
    # brief has no title, no audio and no artwork, so rendering it beside finished
    # songs made the page look broken and inflated every figure on it.
    tracks: list[dict] = []
    in_progress: list[dict] = []
    for t in all_rows:
        target = tracks if lc_mod.is_released(lc_mod.assess(t).stage) else in_progress
        target.append(t)

    album = None
    album_dir = cfg.artwork_root / "albums" / slug
    if album_dir.exists():
        arts = sorted(album_dir.glob("*"))
        album = arts[0] if arts else None

    L: list[str] = [f"# {bblock.get('name', slug)}", ""]
    if album:
        L += [f"![{slug}]({asset_link(out_root, "catalog", album)})", ""]
    if bblock.get("role"):
        L.append(f"**{bblock['role']}**")
        L.append("")
    if bblock.get("disagreement"):
        L += [f"> {bblock['disagreement']}", ""]
    if bblock.get("facet_note"):
        L += [str(bblock["facet_note"]).strip(), ""]

    L += ["## Sound", ""]
    for key, label in (
        ("genre", "Genre"), ("style_prompt", "Style prompt"),
        ("bpm_nominal", "Nominal tempo"), ("vocal", "Vocal"),
    ):
        if sonic.get(key):
            L.append(f"- **{label}** — {str(sonic[key]).strip()}")
    gp = spec.get("glitch_protocol") or {}
    if gp.get("name"):
        L.append(f"- **Glitch protocol** — {gp['name']}: {str(gp.get('reading','')).strip()}")
    L.append("")

    # --- stats -------------------------------------------------------------
    stances = Counter(
        ledger_mod.get_nested(t, "matrix.stance") for t in tracks
        if ledger_mod.get_nested(t, "matrix.stance")
    )
    measured = [t["measured_bpm"] for t in tracks if t.get("measured_bpm")]
    L += ["## By the numbers", "", "| | |", "| --- | --- |"]
    L.append(f"| Releases | {len(tracks)} |")
    if in_progress:
        L.append(f"| In progress | {len(in_progress)} |")
    if measured:
        L.append(f"| Measured tempo range | {min(measured):.0f}–{max(measured):.0f} BPM |")
    reg = spec.get("register") or {}
    L.append(f"| Tempo ceiling | {reg.get('tempo_ceiling') or 'unmeasured'} |")
    if stances:
        L.append(f"| Stances used | {', '.join(f'{k} ×{v}' for k, v in stances.most_common())} |")
    total_glitches = sum(len(t.get("glitch_log") or []) for t in tracks)
    L.append(f"| Logged glitches | {total_glitches} |")
    L.append("")

    # --- matrix ------------------------------------------------------------
    if spec.get("suites"):
        L += ["## The matrix", ""]
        for sid, s in spec["suites"].items():
            used = sum(
                1 for t in tracks if ledger_mod.get_nested(t, "matrix.suite") == sid
            )
            L.append(f"### Suite {sid} — {s.get('name','')}  *({used} track{'s' if used != 1 else ''})*")
            L.append("")
            if s.get("tension"):
                L += [str(s["tension"]).strip(), ""]
            if s.get("juxtaposition"):
                L += [f"*Image:* {str(s['juxtaposition']).strip()}", ""]
            if s.get("anchors"):
                L += [f"*Anchors:* {', '.join(s['anchors'])}", ""]

    # --- tracks ------------------------------------------------------------
    L += ["## Releases", ""]
    for t in tracks:
        tslug = t.get("slug")
        L.append(f"### {t.get('title')}")
        L.append("")
        art = t.get("artwork")
        if art and (cfg.artwork_root / art).exists():
            L.append(f'<img src="{asset_link(out_root, "catalog", cfg.artwork_root / art)}" width="320" alt="{t.get("title")}">')
            L.append("")
        meta = [f"`{t.get('id')}`", f"era `{t.get('era')}`"]
        stage = lc_mod.assess(t).stage
        if stage:
            meta.append(f"stage `{stage}`")
        suite = ledger_mod.get_nested(t, "matrix.suite")
        stance = ledger_mod.get_nested(t, "matrix.stance")
        if suite:
            meta.append(f"suite {suite}")
        if stance:
            meta.append(f"stance {stance}")
        L += [" · ".join(meta), ""]

        url = ledger_mod.get_nested(t, "suno.url")
        if url:
            verified = ledger_mod.get_nested(t, "suno.url_verified")
            note = "" if verified else " *(link constructed from the song id, unverified)*"
            L += [f"[Listen on Suno]({url}){note}", ""]

        stats = _track_stats(t)
        if stats:
            L += ["  \n".join(stats), ""]

        sheet = t.get("lyric_sheet")
        if sheet and (config_mod.REPO_ROOT / sheet).exists():
            body = (config_mod.REPO_ROOT / sheet).read_text(encoding="utf-8")
            if "## Lyrics" in body:
                body = body.split("## Lyrics", 1)[1].strip()
            L += ["<details>", "<summary>Lyrics</summary>", "", "```", body, "```", "",
                  "</details>", ""]

        log = t.get("glitch_log") or []
        if log:
            L += ["<details>", f"<summary>Glitch log ({len(log)})</summary>", ""]
            for g in log:
                anchor = g.get("anchor") or {}
                where = anchor.get("timecode") or anchor.get("section") or "?"
                verified = "measured" if g.get("timecode_verified") else "by ear"
                L.append(f"- **{g.get('protocol')}** at {where} *({verified})* — "
                         f"{g.get('description','')}")
            L += ["", "</details>", ""]
        L.append("---")
        L.append("")

    # --- work in progress ---------------------------------------------------
    # Listed rather than hidden. Omitting it would let the catalogue imply the
    # ledger holds nothing else, which is the same kind of false completeness the
    # inflated count was. Kept separate and plainly labelled, with what each one is
    # actually waiting on, so it reads as a song being written and not as a gap.
    if in_progress:
        L += ["## In progress", "",
              "Not releases. These are in the pipeline and are excluded from every "
              "figure above.", ""]
        for t in in_progress:
            a = lc_mod.assess(t)
            bits = [f"`{t.get('id')}`", f"stage `{a.stage}`"]
            suite = ledger_mod.get_nested(t, "matrix.suite")
            stance = ledger_mod.get_nested(t, "matrix.stance")
            if suite:
                bits.append(f"suite {suite}")
            if stance:
                bits.append(f"stance {stance}")
            L.append(f"### {t.get('title')}")
            L += ["", " · ".join(bits), ""]
            if a.next_stage:
                who = "a human" if a.blocked_on_human else "the tool"
                L += [f"Next: **{a.next_stage}** — {who} advances it."
                      + (f" Waiting on `{'`, `'.join(a.missing)}`." if a.missing else ""),
                      ""]
            L += ["---", ""]
    return "\n".join(L)


def _catalog_index(cfg: Config, out_root: Path) -> str:
    label = context_mod.label_spec()
    lblock = label.get("label") or {}
    results, summary = variety_mod.run(cfg)

    # Releases and work in progress, split per band. Counting every ledger row as
    # a track put 22 on this page while certification checked 21 and the label
    # README said 21 — three numbers, none of them saying which it meant.
    all_tracks: dict[str, list[dict]] = {}
    wip_tracks: dict[str, list[dict]] = {}
    for slug, band in cfg.bands.items():
        rel, wip = [], []
        for t in ledger_mod.load_band_tracks(band):
            (rel if lc_mod.is_released(lc_mod.assess(t).stage) else wip).append(t)
        all_tracks[slug], wip_tracks[slug] = rel, wip

    total = sum(len(v) for v in all_tracks.values())
    total_wip = sum(len(v) for v in wip_tracks.values())
    runtime = sum(
        t.get("duration_s") or 0 for v in all_tracks.values() for t in v
    )

    L: list[str] = []
    # Banner above the heading, which is where a reader's eye starts. Declared in
    # label.yaml so `framework/` stays generic — a label's own artwork has no
    # business being a path inside the toolchain.
    hero = cfg.catalog_hero
    if hero:
        L += [
            f'<img src="{asset_link(out_root, "catalog", hero)}" '
            f'alt="{lblock.get("name", "")}" width="100%">',
            "",
        ]
    L += [f"# {lblock.get('name','Catalogue')}", ""]
    if lblock.get("tagline"):
        L += [f"*{lblock['tagline']}*", ""]
    if lblock.get("axiom"):
        L += [f"> {lblock['axiom']}", ""]

    L += ["## The roster", "", "| Act | Role | Position | Releases |", "| --- | --- | --- | --- |"]
    for slug in cfg.bands:
        spec = context_mod.band_spec(cfg, slug)
        b = spec.get("band") or {}
        count = str(len(all_tracks[slug]))
        if wip_tracks[slug]:
            count += f" *(+{len(wip_tracks[slug])} in progress)*"
        L.append(
            f"| [{b.get('name', slug)}]({slug}.md) | {b.get('role','')} | "
            f"{b.get('disagreement','')} | {count} |"
        )
    L.append("")

    L += ["## Totals", "", "| | |", "| --- | --- |"]
    L.append(f"| Acts | {len(cfg.bands)} |")
    L.append(f"| Releases | {total} |")
    if total_wip:
        L.append(f"| In progress | {total_wip} |")
    L.append(f"| Runtime | {runtime // 60} min |")
    dist = summary.get("label_stances") or {}
    if dist:
        L.append(f"| Stances used | {len(dist)} of {len(summary.get('known_stances') or [])} |")
    L.append("")

    unused = summary.get("unused_stances") or []
    if unused:
        L += [
            "## Never written",
            "",
            f"{len(unused)} of the eleven stances have never been used on this "
            f"roster: {', '.join(f'`{u}`' for u in unused)}.",
            "",
            "Each is an available song.",
            "",
        ]

    canonical = label.get("canonical_phrases") or []
    if canonical:
        L += [
            "## Phrases allowed to cross acts",
            "",
            "Everything else shared between two acts is the roster collapsing into "
            "one voice. These are deliberate:",
            "",
        ]
        L += [f'- "{p}"' for p in canonical]
        L.append("")

    L += [
        "---",
        "",
        "Generated from the ledger by `forge docs catalog`. Every figure here is "
        "computed, not maintained by hand.",
        "",
        "A playable version with inline audio is at `index.html` — GitHub strips "
        "`<audio>` from markdown, so the player only works in the HTML build.",
    ]
    return "\n".join(L)


def _catalog_html(cfg: Config, out_root: Path) -> str:
    """A single playable page. The masters are in the repo, so the player needs no
    third party and no hosting plan — open it from the filesystem."""
    label = (context_mod.label_spec().get("label") or {})
    parts = [
        "<!doctype html><meta charset=utf-8>",
        f"<title>{html.escape(label.get('name','Catalogue'))}</title>",
        "<style>",
        "body{font:16px/1.55 system-ui,sans-serif;max-width:52rem;margin:2rem auto;"
        "padding:0 1rem;background:#111;color:#eee}",
        "h1{border-bottom:2px solid #444;padding-bottom:.3rem}",
        "h2{margin-top:2.5rem;color:#fff}",
        ".track{display:flex;gap:1rem;margin:1.5rem 0;padding:1rem;background:#1b1b1b;"
        "border-radius:8px;align-items:flex-start}",
        ".track img{width:140px;height:140px;object-fit:cover;border-radius:4px;flex:none}",
        ".meta{color:#999;font-size:.85rem;margin:.25rem 0}",
        "audio{width:100%;margin-top:.6rem}",
        "a{color:#8bd}",
        # The banner is a printed artefact on a bone-white ground and this page is
        # near-black, so it reads as a lit panel rather than a header bleeding into
        # the background. Left deliberately full-width and unfaded.
        ".hero{display:block;width:100%;height:auto;border-radius:6px;margin:0 0 1.5rem}",
        # Work in progress is deliberately not styled as a track: no cover slot, no
        # player, recessed and rule-marked. A brief rendered as a .track looked like
        # a release whose audio had failed to load.
        ".wip{margin:1.5rem 0;padding:.7rem 1rem;background:#161616;"
        "border-left:3px solid #444;border-radius:4px;color:#8a8a8a;font-size:.9rem}",
        "</style>",
    ]
    # Same image as the markdown index: the player is the catalogue's playable
    # build, not a second catalogue, so it should not have a second identity. Same
    # abstain rule too — no banner declared, or declared and absent, means no tag.
    hero = cfg.catalog_hero
    if hero:
        parts.append(
            f'<img class=hero src="{asset_link(out_root, "catalog", hero)}" '
            f'alt="{html.escape(label.get("name", ""))}">'
        )
    parts.append(f"<h1>{html.escape(label.get('name','Catalogue'))}</h1>")
    if label.get("axiom"):
        parts.append(f"<p><em>{html.escape(label['axiom'])}</em></p>")
    parts.append(
        "<p class=meta>Audio plays from the committed masters. No third party, "
        "no hosting — this file works from disk.</p>"
    )

    for slug in cfg.bands:
        spec = context_mod.band_spec(cfg, slug)
        b = spec.get("band") or {}
        parts.append(f"<h2>{html.escape(b.get('name', slug))}</h2>")
        if b.get("disagreement"):
            parts.append(f"<p><em>{html.escape(b['disagreement'])}</em></p>")
        rows = ledger_mod.load_band_tracks(cfg.bands[slug])
        released, wip = [], []
        for t in rows:
            (released if lc_mod.is_released(lc_mod.assess(t).stage) else wip).append(t)
        for t in released:
            art = t.get("artwork")
            audio = t.get("audio")
            parts.append("<div class=track>")
            if art and (cfg.artwork_root / art).exists():
                parts.append(
                    f'<img src="{asset_link(out_root, "catalog", cfg.artwork_root / art)}" alt="">'
                )
            parts.append("<div style=flex:1>")
            parts.append(f"<strong>{html.escape(str(t.get('title')))}</strong>")
            bits = [t.get("id"), f"era {t.get('era')}"]
            if t.get("measured_bpm"):
                bits.append(f"{t['measured_bpm']:.0f} BPM measured")
            parts.append(f"<div class=meta>{html.escape(' · '.join(map(str, bits)))}</div>")
            url = ledger_mod.get_nested(t, "suno.url")
            if url:
                parts.append(f'<div class=meta><a href="{html.escape(url)}">Suno</a></div>')
            if audio and (cfg.audio_root / audio).exists():
                parts.append(
                    f'<audio controls preload=none '
                    f'src="{asset_link(out_root, "catalog", cfg.audio_root / audio)}"></audio>'
                )
            else:
                # Now reachable only for a RELEASED track whose master is missing,
                # which certification reports as a gap. Before the split it fired
                # on every brief, so the one case that means something was buried
                # among cases that meant nothing.
                parts.append("<div class=meta>no master on disk</div>")
            parts.append("</div></div>")

        for t in wip:
            a = lc_mod.assess(t)
            bits = [str(t.get("id")), f"stage {a.stage}"]
            if a.next_stage:
                bits.append(
                    f"next: {a.next_stage}"
                    f" ({'human' if a.blocked_on_human else 'tool'})"
                )
            parts.append(
                "<div class=wip><strong>"
                f"{html.escape(str(t.get('title')))}</strong><br>"
                f"In progress — {html.escape(' · '.join(bits))}</div>"
            )
    return "\n".join(parts) + "\n"


def build_catalog(cfg: Config, out_root: Path) -> DocSet:
    ds = DocSet(kind="catalog")
    ds.files.append(DocFile("catalog/README.md", _catalog_index(cfg, out_root)))
    for slug in cfg.bands:
        ds.files.append(DocFile(f"catalog/{slug}.md", _catalog_band(cfg, slug, out_root)))
    ds.files.append(DocFile("catalog/index.html", _catalog_html(cfg, out_root)))
    if not assets_reachable(out_root):
        ds.files.append(DocFile("catalog/ASSETS-NOTE.md", ASSETS_NOTE))
    return ds


ASSETS_NOTE = """# Asset links in this build

This catalogue was generated outside the repository, so artwork and audio cannot
be reached by a relative path. Links fall back to absolute `file://` URLs, which
work on the machine that generated them and nowhere else.

If these pages are going somewhere other people will read — a wiki, a static
host — the assets need to travel with them, or the links need rewriting to
wherever the images and masters actually live.
"""


def format_result(result: dict) -> str:
    lines = ["=" * 78, f"DOCS  {result['kind']}", "=" * 78]
    lines.append(f"root: {result['root']}")
    lines.append(f"{result['count']} files")
    lines.append("")
    for f in result["files"]:
        lines.append(f"   {f}")
    return "\n".join(lines)
