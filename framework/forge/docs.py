def _command_reference() -> str:
    """Generated by walking the real parser. A hand-written command reference is
    wrong within a week and nobody notices until someone follows it."""
    from .cli import build_parser

    parser = build_parser()
    subs = [
        a for a in parser._actions
        if a.__class__.__name__ == "_SubParsersAction"
    ]
    lines = [
        "# Command reference",
        "",
        "Generated from the argument parser — this file cannot drift from the code.",
        "",
        "```bash",
        "python3 -m framework.forge <command> [options]",
        "```",
        "",
        "Commands that report accept `--json`. Structured output is the primary",
        "rendering, since the tool is normally driven by an agent; the formatted",
        "view is a second rendering of the same data.",
        "",
    ]
    if not subs:
        return "\n".join(lines)

    for name, sub in sorted(subs[0].choices.items()):
        lines.append(f"## `{name}`")
        lines.append("")
        if sub.description or sub.prog:
            help_text = subs[0]._choices_actions
            match = next((c for c in help_text if c.dest == name), None)
            if match and match.help:
                lines.append(match.help)
                lines.append("")
        opts = []
        for act in sub._actions:
            if act.dest in ("help",):
                continue
            flags = ", ".join(f"`{o}`" for o in act.option_strings) or f"`{act.dest}`"
            choices = f" — one of {', '.join(map(str, act.choices))}" if act.choices else ""
            required = " **(required)**" if getattr(act, "required", False) else ""
            opts.append(f"| {flags} | {act.help or ''}{choices}{required} |")
        if opts:
            lines.append("| Option | Meaning |")
            lines.append("| --- | --- |")
            lines.extend(opts)
            lines.append("")
    return "\n".join(lines)


def _lifecycle_doc() -> str:
    lines = [
        "# The song lifecycle",
        "",
        "Generated from `lifecycle.py`.",
        "",
        "A song is tracked from raw input to adjudicated glitch log. **Stage is",
        "derived from what exists on disk**, never read from a field somebody has",
        "to remember to update — a recorded stage that disagrees with reality is",
        "worse than no stage at all.",
        "",
        "`imported` sits outside the sequence. Legacy tracks enter there rather",
        "than at `mastered`, because they genuinely did not go through this",
        "pipeline and inventing a spark for them would fabricate provenance.",
        "",
        "| # | Stage | Gate | Requires | Summary |",
        "| --- | --- | --- | --- | --- |",
    ]
    for s in lc_mod.STAGES:
        order = "—" if s.order < 0 else str(s.order)
        req = ", ".join(f"`{r}`" for r in s.requires) or "—"
        lines.append(f"| {order} | `{s.id}` | {s.gate} | {req} | {s.summary} |")

    lines += ["", "## What each human gate asks for", ""]
    for s in lc_mod.STAGES:
        if s.gate == lc_mod.HUMAN and s.asks:
            lines += [f"### `{s.id}`", "", s.asks, ""]
    return "\n".join(lines)


ARCHITECTURE = """\
# Architecture

## Two layers

```
framework/     generic — lift this into any label project untouched
  forge/         the Python toolchain
  prompts/       the prompt library, as data
  stances.yaml   the rhetorical stance taxonomy
label/         one label's instance
  label.yaml     roster, asset roots, eras, canonical phrases
  substrate.md   the shared biography the acts draw on
  bands/<slug>/  band.yaml, dossier.md, retired.yaml, tracks.yaml, lyrics/
  audio/         masters, committed
  artwork/       covers, committed
  sparks/        raw human input — gitignored
  briefs/        derived briefs — committed
```

The split is what makes the repo usable as a template: `framework/` knows nothing
about any particular label.

## Three runtimes, one prompt library

Inference happens three ways, and all three render the same templates:

| Runtime | Credentials | How |
| --- | --- | --- |
| **agent** | none | `forge infer --mode agent` renders; the agent in your editor acts |
| **api** | your own key, from the environment | `forge infer --mode api` |
| **notebook** | none | `forge bundle export` writes sources for NotebookLM |

If each runtime carried its own copy of the wording they would drift, and the
same brief would produce different songs depending on where it ran. The template
is the artefact; the runtime is only delivery.

The notebook rendering is the clearest demonstration: the same `generate-song`
template produces a ~17,000-character API prompt with the dossier substituted
in, and a ~4,700-character notebook prompt that says *"See 03-dossier.md in this
notebook's sources."*

## The data model

`label/bands/<slug>/tracks.yaml` is the spine. One entry per song, carrying:

- **identity** — id, title, slug, band, era
- **assets** — audio and artwork paths plus their `sha256`
- **brief** — matrix suite, rhetorical stance
- **suno** — style prompt, declared BPM and key, song id and url
- **measurement** — `measured_bpm`, the full `analysis` block
- **glitch_log** — adjudicated anomalies with verified timecodes
- **lifecycle** — current stage and append-only history
- **provenance** — spark id, brief, prompt template and version, model

### Declared and measured are kept apart

`declared_bpm` and `measured_bpm` are separate fields, always. A measurement and
a declaration are different claims, and merging them destroys the only evidence
that they disagree — which they do on nine of twenty-one tracks in the reference
catalogue.

### Assets are fingerprinted

Every master and cover carries a `sha256`. The ledger stores measurements derived
from those files, so without a hash the numbers degrade silently: re-export a
different render of the same title and every timecode stays put while the thing
it describes changes underneath. `forge reconcile` reports drift.

## Why the ledger is data and not prose

The predecessor of this system kept its metadata ledger inside notebook
documents, as prose. Prose ledgers cannot be checked. An audit run against one
reported `PASS` for four files, three of which did not exist — the model had no
way to distinguish verifying a file from describing one.

Everything checkable is therefore checked in Python, and only genuine judgement
is delegated to a model. That division runs through the whole tool:

| Computed | Delegated |
| --- | --- |
| burned phrase reused | is the stance held for the whole song |
| bare or overloaded cue | is the narrator on-model |
| suite anchor missing | does a line contradict the substrate |
| tempo above measured ceiling | is the addressee specific enough |
| n-gram shared with another act | is it any good |

## The gates

- `reconcile` — audio, artwork, lyrics and ledger agree; hashes match; YAML parses;
  naming convention holds. Era- and stage-aware, so work in progress is reported
  without failing the build.
- `variety` — distribution of stance, suite, tempo, key and style prompt. The
  predecessor audit had six gates and all six measured *format*, which is
  trivially satisfiable; it passed a catalogue where four tracks shared a BPM, a
  key and a byte-identical sonic blueprint.
- `mine` — phrases a band has spent, and phrases crossing between acts.
- `prompt lint` — every slot used is declared and every slot declared is used.
"""

CONCEPTS = """\
# Concepts

## Suites and stances — two axes, not one

A **suite** is what a song is about. A **stance** is how it is spoken. They are
independent, and conflating them is the mistake this system exists to correct.

A lyrical matrix constrains vocabulary. It does not constrain syntax, and syntax
is where sameness lives. In the reference catalogue one act had four thematic
suites and six songs, and all six were the same speech act: second-person
accusation. The topic rotated; the posture never did. Another opened three
separate bridges on *"A deep lack of ___"* — not a vocabulary problem, and no
lexicon check would ever have caught it.

Eleven stances against four or five suites gives forty-plus distinct premises per
act instead of four, and the stance is what changes the sentences rather than
just the nouns.

## The narrator dossier

Each act fixes **who speaks, from where, at what hour, to whom, what they want,
and what they cannot admit.**

A fixed speaker generates consistent diction automatically, because word choice
follows from position. It does more for voice consistency than any word list.

Acts are differentiated by **room, hour and addressee** — concrete and checkable
— rather than by adjectives. In the reference roster four of five acts are alone;
the one with a crowd in the room is the only one that can be patient, and that
falls out of the room rather than being asserted.

The *cannot admit* field turns out to hold the most valuable unwritten material on
a roster: the only things the speaker is actually hiding.

## The shared substrate

When a roster is several facets of one person rather than several characters,
consistency stops depending on remembering invented lore and starts depending on
one set of real facts read several ways. Far more robust — and it lets one event
be written several times without repetition, which is the strongest format the
format offers.

## Register — aiming the glitch

Each act carries a **measured** breakage profile: the tempo ceiling and the
lexical shapes that break that particular voice, with the evidence.

This converts the Glitch Axiom from post-hoc rationalisation into an instrument.
If you know where a voice breaks, a hard word becomes *placeable*: put the
polysyllable where a slur reads as emphasis, and never on a word the line depends
on. In the reference catalogue one track lost the word *faders* to a slur and the
line lost its meaning with it; another lost *analog*, the word its own song was
named after. Both were placement decisions nobody made.

Where a register says **unmeasured**, it is genuinely unknown. Guessing a ceiling
and presenting it as known is the failure the measurement layer exists to end.

## The Glitch Axiom

Synthesis failures are kept, named under the act's own protocol, and left in the
mix. Punk did not overcome the limitations of cheap four-track recording; it made
them the sound.

Two consequences the tool enforces:

- The analyser finds candidates. **It never decides.** Which failures are badges
  of honour is a human judgement, and automating it would gut the idea.
- A glitch log is written *after* a render, never before. One written in advance
  is fabricated evidence.

## Eras

A label whose axiom is *leave the glitch in* does not sanitise its own back
catalogue. Tracks written before the standards existed are tagged
`era: pre-standard` and exempted from the matrix, stance and lexicon gates. They
still get lyric sheets and glitch logs. Their repetitions are not a compliance
failure — they are the corpus the burned lists are mined from.

## Sparks and provenance

The **spark** is the rawest human input: the argument you actually had, the phrase
you cannot place. `label/sparks/` is gitignored, because git is permanent and a
repo may go public. The committed brief references the spark by id and copies
nothing from it — a "derived summary" would leak it back in through the side door.

Provenance records which prompt template and version, which model, and which mode
produced each draft. The point is not bookkeeping: it means *"why is this song
like this?"* has an answer.

## Informed elicitation

Every human gate asks for exactly what it needs, informed by what the tool
already knows. The difference is between a form and a collaborator:

> **Form:** What do you want to write about?
>
> **Informed:** This act is 3-for-3 on accusation and has never used procedure.
> Suite B is its core suite and its least mined. Measured tempo 152–185 with no
> failures, so there is headroom the D-beat act does not have.

Both are questions. Only one is worth answering.
"""

